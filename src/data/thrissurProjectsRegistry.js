const THRISSUR_BY_SLUG = new Map();
const THRISSUR_BY_ID = new Map();
THRISSUR_REGISTRY_PROJECTS.forEach((p) => {
  THRISSUR_BY_SLUG.set(p.slug, p);
  THRISSUR_BY_ID.set(String(p.id), p);
  const shortSlug = p.slug.replace(/-pid-\d+$/, "");
  if (!THRISSUR_BY_SLUG.has(shortSlug)) {
    THRISSUR_BY_SLUG.set(shortSlug, p);
  }
});

export const THRISSUR_ALL_SLUGS = THRISSUR_REGISTRY_PROJECTS.map((p) => p.slug);

export const THRISSUR_PROJECT_COORDINATES = {};
THRISSUR_REGISTRY_PROJECTS.forEach((p) => {
  if (typeof p.lat === "number" && typeof p.lng === "number") {
    THRISSUR_PROJECT_COORDINATES[p.slug] = {
      lat: p.lat,
      lng: p.lng,
      locality: p.location,
      city: "thrissur",
      cityName: "Thrissur",
      propertyType: p.type || "Apartment",
      verified: true,
    };
    THRISSUR_PROJECT_COORDINATES[p.id] = THRISSUR_PROJECT_COORDINATES[p.slug];
  }
});

function buildAmenitiesForThrissur(features = []) {
  return (features || []).map((feat) => {
    const fLower = String(feat).toLowerCase();
    let cat = "Lifestyle";
    let icon = "Sparkles";
    if (fLower.includes("pool") || fLower.includes("gym") || fLower.includes("fitness") || fLower.includes("yoga") || fLower.includes("jogging") || fLower.includes("spa")) {
      cat = "Wellness"; icon = "Dumbbell";
    } else if (fLower.includes("security") || fLower.includes("cctv") || fLower.includes("intercom") || fLower.includes("gated") || fLower.includes("fire")) {
      cat = "Security"; icon = "Shield";
    } else if (fLower.includes("club") || fLower.includes("hall") || fLower.includes("theatre") || fLower.includes("lounge") || fLower.includes("party")) {
      cat = "Social"; icon = "Coffee";
    } else if (fLower.includes("garden") || fLower.includes("tree") || fLower.includes("ev") || fLower.includes("rain") || fLower.includes("solar") || fLower.includes("park")) {
      cat = "Eco"; icon = "Zap";
    } else if (fLower.includes("court") || fLower.includes("sport") || fLower.includes("track") || fLower.includes("cricket") || fLower.includes("badminton")) {
      cat = "Sports"; icon = "Trophy";
    }
    return { name: feat, category: cat, icon };
  });
}

function buildConfigurationsForThrissurProject(p) {
  const extras = THRISSUR_REGISTRY_EXTRAS[p.slug] || {};
  const plans = [];

  if (Array.isArray(extras.unitPlan) && extras.unitPlan.length > 0) {
    extras.unitPlan.forEach((grp) => {
      const units = Array.isArray(grp.data) ? grp.data : [];
      units.forEach((u, idx) => {
        const carpet = u.carpet_area ? `${u.carpet_area} sq.ft.` : (p.carpetArea !== "On Request" ? p.carpetArea : "On Request");
        const builtUp = u.built_up_area ? `${u.built_up_area} sq.ft.` : (p.builtUpArea !== "On Request" ? p.builtUpArea : carpet);
        const rawPrice = u.price ? String(u.price).replace(/^₹\s*/i, "").trim() : p.price;
        const imgUrl = u.two_d_url || u.three_d_url || p.images?.[0] || "/images/placeholder-property.jpg";
        plans.push({
          type: grp.label || u.flat_type || p.flatTypes,
          bhk: grp.label || u.flat_type || p.flatTypes,
          carpetArea: carpet,
          superArea: builtUp,
          area: builtUp !== "On Request" ? builtUp : carpet,
          price: rawPrice ? (rawPrice === "On Request" ? "On Request" : `₹ ${rawPrice}`) : (p.price === "On Request" ? "On Request" : `₹ ${p.price}`),
          specs: {
            bedrooms: parseInt(String(grp.label || u.flat_type || ""), 10) || 2,
            bathrooms: parseInt(String(grp.label || u.flat_type || ""), 10) || 2,
            balconies: 1,
            parking: "Covered Parking",
          },
          facing: "East / North Facing",
          description: `Verified configuration at ${p.name}, ${p.location}.`,
          propertyType: u.property_type || p.type || "Apartment",
          image: imgUrl,
          layoutImage: imgUrl,
          key: `${p.id}-${grp.label || "unit"}-${u.id || idx}`,
        });
      });
    });
  }

  if (plans.length === 0 && Array.isArray(extras.configurationSummary) && extras.configurationSummary.length > 0) {
    extras.configurationSummary.forEach((c, idx) => {
      const areaVal = c.carpet_area || (p.carpetArea !== "On Request" ? p.carpetArea : (p.builtUpArea || "On Request"));
      const rawPrice = c.price ? String(c.price).replace(/^₹\s*/i, "").trim() : p.price;
      const imgUrl = p.images?.[0] || "/images/placeholder-property.jpg";
      plans.push({
        type: c.flat_type_name || p.flatTypes,
        bhk: c.flat_type_name || p.flatTypes,
        carpetArea: areaVal,
        superArea: p.builtUpArea || areaVal,
        area: areaVal,
        price: rawPrice === "On Request" ? "On Request" : `₹ ${rawPrice}`,
        specs: { bedrooms: 2, bathrooms: 2, balconies: 1, parking: "Covered Parking" },
        facing: "East / North Facing",
        description: `Verified configuration at ${p.name}, ${p.location}.`,
        propertyType: p.type || "Apartment",
        image: imgUrl,
        layoutImage: imgUrl,
        key: `${p.id}-cfg-${idx}`,
      });
    });
  }

  if (plans.length === 0) {
    const areaVal = p.carpetArea !== "On Request" ? p.carpetArea : (p.builtUpArea || "On Request");
    const imgUrl = p.images?.[0] || "/images/placeholder-property.jpg";
    plans.push({
      type: p.flatTypes || p.type || "Residential",
      bhk: p.flatTypes || p.type || "Residential",
      carpetArea: p.carpetArea || "On Request",
      superArea: p.builtUpArea || areaVal,
      area: areaVal,
      price: p.price && p.price !== "On Request" ? `₹ ${p.price}` : "On Request",
      specs: { bedrooms: 2, bathrooms: 2, balconies: 1, parking: "Covered Parking" },
      facing: "East / North Facing",
      description: `Verified configuration at ${p.name}, ${p.location}.`,
      propertyType: p.type || "Apartment",
      image: imgUrl,
      layoutImage: imgUrl,
      key: `${p.id}-default`,
    });
  }

  return plans;
}

