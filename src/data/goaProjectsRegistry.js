const GOA_BY_SLUG = new Map();
const GOA_BY_ID = new Map();
GOA_REGISTRY_PROJECTS.forEach((p) => {
  GOA_BY_SLUG.set(p.slug, p);
  GOA_BY_ID.set(String(p.id), p);
  const shortSlug = p.slug.replace(/-pid-\d+$/, "");
  if (!GOA_BY_SLUG.has(shortSlug)) {
    GOA_BY_SLUG.set(shortSlug, p);
  }
});

export const GOA_ALL_SLUGS = GOA_REGISTRY_PROJECTS.map((p) => p.slug);

export const GOA_PROJECT_COORDINATES = {};
GOA_REGISTRY_PROJECTS.forEach((p) => {
  if (typeof p.lat === "number" && typeof p.lng === "number") {
    GOA_PROJECT_COORDINATES[p.slug] = {
      lat: p.lat,
      lng: p.lng,
      locality: p.location,
      city: "goa",
      cityName: "Goa",
      propertyType: p.type || "Apartment",
      verified: true,
    };
    GOA_PROJECT_COORDINATES[p.id] = GOA_PROJECT_COORDINATES[p.slug];
  }
});

function buildConfigurationsForGoaProject(p) {
  const extras = GOA_REGISTRY_EXTRAS[p.slug] || {};
  const plans = [];

  if (Array.isArray(extras.unitPlan) && extras.unitPlan.length > 0) {
    extras.unitPlan.forEach((grp) => {
      const units = Array.isArray(grp.data) ? grp.data : [];
      units.forEach((u, idx) => {
        const areaText = u.carpet_area
          ? `${u.carpet_area} sq.ft. (Carpet)`
          : u.built_up_area
            ? `${u.built_up_area} sq.ft. (Built-up)`
            : p.carpetArea !== "On Request"
              ? p.carpetArea
              : p.builtUpArea;
        plans.push({
          type: grp.label || u.flat_type || p.flatTypes,
          area: areaText || "On Request",
          price: u.price ? (String(u.price).startsWith("₹") ? u.price : `₹ ${u.price}`) : p.price,
          propertyType: u.property_type || p.type || "Apartment",
          image: u.two_d_url || u.three_d_url || p.images?.[0] || "/images/placeholder-property.jpg",
          key: `${p.id}-${grp.label || "unit"}-${u.id || idx}`,
        });
      });
    });
  }

  if (plans.length === 0 && Array.isArray(extras.configurationSummary) && extras.configurationSummary.length > 0) {
    extras.configurationSummary.forEach((c, idx) => {
      plans.push({
        type: c.flat_type_name || p.flatTypes,
        area: c.carpet_area || p.carpetArea || "On Request",
        price: c.price ? (String(c.price).startsWith("₹") ? c.price : `₹ ${c.price}`) : p.price,
        propertyType: p.type || "Apartment",
        image: p.images?.[0] || "/images/placeholder-property.jpg",
        key: `${p.id}-cfg-${idx}`,
      });
    });
  }

  if (plans.length === 0) {
    plans.push({
      type: p.flatTypes || p.type || "Residential",
      area: p.carpetArea !== "On Request" ? p.carpetArea : (p.builtUpArea || "On Request"),
      price: p.price || "On Request",
      propertyType: p.type || "Apartment",
      image: p.images?.[0] || "/images/placeholder-property.jpg",
      key: `${p.id}-default`,
    });
  }

  return plans;
}

export function getGoaProjectBySlug(rawSlug) {
  if (!rawSlug) return null;
  const clean = decodeURIComponent(String(rawSlug)).toLowerCase().trim();
  let p = GOA_BY_SLUG.get(clean) || GOA_BY_ID.get(clean);
  if (!p) {
    const pidMatch = clean.match(/-pid-(\d+)$/) || clean.match(/-(\d+)$/);
    if (pidMatch) p = GOA_BY_ID.get(pidMatch[1]);
  }
  if (!p) return null;

  const extras = GOA_REGISTRY_EXTRAS[p.slug] || {};
  const specs = [
    { label: "Configurations", value: p.flatTypes || "On Request" },
    { label: "Carpet Area", value: p.carpetArea || "On Request" },
    { label: "Built-up Area", value: p.builtUpArea || "On Request" },
    { label: "Possession", value: p.possession || "Under Construction" },
    { label: "Project Status", value: p.status || "Under Construction" },
    { label: "Project Area", value: p.projectArea || "On Request" },
    { label: "Average Rate", value: p.avgPrice || "On Request" },
    { label: "Goa RERA ID", value: p.rera || "Not Available" },
  ];

  const reraIds = (p.rera_informations && p.rera_informations.length > 0)
    ? p.rera_informations
    : (p.rera && p.rera !== "Not Available"
        ? p.rera.split(",").map((id) => ({ rera_id: id.trim() }))
        : []);

  const otherGoa = GOA_REGISTRY_PROJECTS.filter((item) => item.slug !== p.slug).slice(0, 4);

  return {
    id: p.id,
    slug: p.slug,
    title: p.name,
    name: p.name,
    builder: p.builder,
    builderLogo: p.builderLogo,
    developerSlug: p.developerSlug,
    city: "goa",
    cityName: "Goa",
    region: p.region,
    locality: p.locality,
    location: p.location,
    fullAddress: p.fullAddress,
    lat: p.lat,
    lng: p.lng,
    price: p.price,
    priceRange: p.priceRange,
    priceNumeric: p.priceNumeric,
    avgPrice: p.avgPrice,
    flatTypes: p.flatTypes,
    carpetArea: p.carpetArea,
    builtUpArea: p.builtUpArea,
    projectArea: p.projectArea,
    possession: p.possession,
    status: p.status,
    rera: p.rera,
    rera_informations: reraIds,
    stateReraLink: extras.stateReraLink || "https://rera.goa.gov.in/reraApp/#_",
    tag: p.tag,
    type: p.type,
    isExclusive: p.isExclusive,
    isRera: p.isRera,
    rating: 4.7,
    reviewsCount: 84,
    images: p.images,
    overview: p.description,
    highlights: [
      `Located in ${p.location}, Goa`,
      `Developed by ${p.builder}`,
      p.rera && p.rera !== "Not Available" ? `Goa RERA Registered: ${p.rera}` : "Verified PropertyPistol Goa Listing",
      `Configurations: ${p.flatTypes || p.type}`,
      `Possession: ${p.possession}`,
    ],
    specs,
    amenities: p.features && p.features.length > 0 ? p.features : ["24/7 Security", "Landscaped Gardens", "Car Parking"],
    amenitiesDetails: extras.amenitiesDetails || [],
    floorPlans: buildConfigurationsForGoaProject(p),
    bankOffers: extras.bankOffers || [],
    developerInfo: {
      name: p.builder,
      slug: p.developerSlug,
      logo: p.builderLogo,
      description: p.builderDescription || `${p.builder} develops verified residential communities across Goa.`,
    },
    nearbyProjects: otherGoa.map((o) => ({
      id: o.id,
      slug: o.slug,
      name: o.name,
      title: o.name,
      location: o.location,
      price: o.price,
      flatTypes: o.flatTypes,
      images: o.images,
      city: "goa",
    })),
    referenceUrl: p.referenceUrl,
  };
}
