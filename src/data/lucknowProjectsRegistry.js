export function getLucknowProjectBySlug(slug) {
  if (!slug) return null;
  const clean = String(slug).toLowerCase().trim();
  return LUCKNOW_REGISTRY_PROJECTS.find(p => {
    return p.slug.toLowerCase() === clean || 
           String(p.id) === clean || 
           p.slug.replace(/-pid-\d+$/, '').toLowerCase() === clean ||
           p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-') === clean;
  }) || null;
}

