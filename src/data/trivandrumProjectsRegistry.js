const TRIVANDRUM_BY_SLUG = new Map();
const TRIVANDRUM_BY_ID = new Map();
TRIVANDRUM_REGISTRY_PROJECTS.forEach((p) => {
  TRIVANDRUM_BY_SLUG.set(p.slug, p);
  TRIVANDRUM_BY_ID.set(String(p.id), p);
  const shortSlug = p.slug.replace(/-pid-\d+$/, "");
  if (!TRIVANDRUM_BY_SLUG.has(shortSlug)) {
    TRIVANDRUM_BY_SLUG.set(shortSlug, p);
  }
});

export const TRIVANDRUM_ALL_SLUGS = TRIVANDRUM_REGISTRY_PROJECTS.map((p) => p.slug);

